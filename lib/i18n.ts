export const dict: Record<Lang, Record<Key, string>> = { ar, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict[DEFAULT_LANG][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Label for a database code (e.g. category "mvt"): translated when "<prefix>.<code>" exists, otherwise the raw code. */
export function labelOf(lang: Lang, prefix: string, code: string): string {
  const k = `${prefix}.${code}`;
  return k in dict.ar ? translate(lang, k as Key) : code;
}
